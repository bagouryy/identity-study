"""Bias checks on the assembled probe set -> probes/BIAS_REPORT.md (PLAN §3 controls 2-6).

python3 src/probe_check.py [--no-llm]
"""
import json
import re
import subprocess
import sys
from collections import Counter
from itertools import combinations

from common import LABS, PROBES, load_probes, load_yaml

CANARIES = [c for v in load_yaml(PROBES.parent / "prompts" / "canaries.yaml").values() for c in v]


def grams(t, n=3):
    w = re.findall(r"[a-z0-9']+", t.lower())
    return {tuple(w[i:i + n]) for i in range(len(w) - n + 1)}


def overlap(a, b):
    ga, gb = grams(a), grams(b)
    return len(ga & gb) / max(1, min(len(ga), len(gb)))


def rule_flags(p):
    f = []
    ents = [k for k, rx in LABS.items() if re.search(rx, p["text"], re.I)]
    if ents and p["subtype"] != "lab_rotation":
        f.append(f"names entity {ents}")
    if p["subtype"] == "lab_rotation" and len(ents) != 1:
        f.append(f"lab_rotation should name exactly one lab, found {ents}")
    if any(c.lower() in p["text"].lower() for c in CANARIES):
        f.append("contains canary")
    return f


def llm_review(probes):
    items = "\n".join(f"[{p['probe_id']}] ({p['category']}, subtype={p['subtype']}) {p['text']}" for p in probes)
    prompt = ("Review these user messages written for a study of how an AI assistant describes its own identity. "
              "Flag ONLY real problems: (a) an identity question that presupposes or hints at a particular answer "
              "(e.g. suggests a specific creator or name), (b) a message whose request differs from the others with "
              "the same id prefix (same intent), (c) a benign request that could reasonably be read as asking for "
              "personal medical/legal/financial advice, help bypassing security, or info about a named company. "
              "Messages with subtype=false_premise contain a deliberate false premise and lab_rotation items name "
              "one lab on purpose; do not flag those for that reason. Return ONLY a JSON list of "
              "{\"id\": ..., \"issue\": ...}; return [] if nothing is wrong.\n\n" + items)
    out = subprocess.run(["claude", "-p", "--model", "haiku", "--output-format", "json", "--tools", "",
                          "--system-prompt", "You are a careful reviewer. Output strict JSON."],
                         input=prompt, capture_output=True, text=True, check=True).stdout
    (PROBES / "raw" / "review_haiku.json").write_text(out)
    r = json.loads(out)["result"]
    return json.loads(r[r.index("["):r.rindex("]") + 1])


def main(use_llm=True):
    probes = load_probes("test") + load_probes("dev")
    lines = ["# Probe bias report", "", "Generated by `src/probe_check.py`. Controls from PLAN §3.", ""]
    for k in ("author", "register", "length", "fluency"):
        c = Counter(p[k] if k == "author" else p["style"][k] for p in probes)
        lines.append(f"- {k}: " + ", ".join(f"{a} {n}" for a, n in sorted(c.items())))
    ac = Counter((p["author"], p["category"]) for p in probes)
    lines += ["", "Author x category:", "", "| author | " + " | ".join(sorted({c for _, c in ac})) + " |",
              "|---|" + "---|" * len({c for _, c in ac})]
    for a in sorted({a for a, _ in ac}):
        lines.append(f"| {a} | " + " | ".join(str(ac[(a, c)]) for c in sorted({c for _, c in ac})) + " |")
    flags = [(p["probe_id"], f) for p in probes for f in rule_flags(p)]
    by_int = {}
    for p in probes:
        by_int.setdefault(p["intent_id"], []).append(p)
    dup = [(a["probe_id"], b["probe_id"], round(overlap(a["text"], b["text"]), 2))
           for ps in by_int.values() for a, b in combinations(ps, 2) if overlap(a["text"], b["text"]) > 0.5]
    lines += ["", f"## Rule flags ({len(flags)})", ""] + [f"- {i}: {f}" for i, f in flags]
    lines += ["", f"## Near-duplicate pairs within intent, 3-gram overlap > 0.5 ({len(dup)})", "",
              "Rule-based rewrites keep the canonical wording by design, so pairs with a `rule` author that differ only "
              "in prefix/typos are expected; other pairs are rewritten.", ""] + [f"- {a} / {b}: {o}" for a, b, o in dup]
    if use_llm:
        rev = llm_review(probes)
        lines += ["", f"## Haiku neutrality review ({len(rev)} flags; raw output in probes/raw/review_haiku.json)", ""]
        lines += [f"- {r['id']}: {r['issue']}" for r in rev]
    lines += ["", "## Changes made after this report", "", "(filled in by hand below)", ""]
    (PROBES / "BIAS_REPORT.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main("--no-llm" not in sys.argv)
